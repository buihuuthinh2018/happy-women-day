import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const context={};vm.runInNewContext(await readFile('dist/letter-gestures.js','utf8'),context);
const {canStart}=context.LetterGestures;
const phone={x:200,y:300,width:390,height:844,paper:{left:40,right:350,top:100,bottom:690}};
test('only the interior of the paper accepts one-finger gestures',()=>{assert.equal(canStart(phone),true);assert.equal(canStart({...phone,x:20}),false);assert.equal(canStart({...phone,x:375}),false);assert.equal(canStart({...phone,y:800}),false);assert.equal(canStart({...phone,y:50}),false);});
test('system bottom area stays excluded even with a tall paper',()=>{assert.equal(canStart({...phone,y:780,paper:{...phone.paper,bottom:830}}),false);});
test('controls, animation, multi-touch and zoom do not initiate page turns',()=>{for(const extra of [{interactive:true},{busy:true},{touches:2},{scale:1.5}])assert.equal(canStart({...phone,...extra}),false);});
